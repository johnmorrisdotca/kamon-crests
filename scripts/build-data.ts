// Writes everything generated from the crest definitions: each crest's module and its construction, the table of
// loaders, the records, and the catalogue and Japanese-string lists in docs/. Run it with `pnpm data`; CI runs it
// again and fails if anything it writes differs from what is committed.
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";

import { staticSvg } from "../src/render.ts";
import { ARRANGEMENTS, FRAMES, MOTIFS, TURNS } from "../src/parts.ts";
import { make } from "./construct/make.ts";
import { statsOf } from "./construct/stats.ts";
import { ALL } from "./crests/index.ts";
import { USED_BY } from "./crests/used-by.ts";
import { BUDGET_BYTES, CEILING_BYTES } from "./data-config.ts";
import { WORDS } from "../demo/words.js";

const HEADER = "// Generated by scripts/build-data.ts. Do not edit by hand: change the crest's definition in scripts/crests and run pnpm data.\n";
const frames = new Set(FRAMES.map((one) => one.id));
const motifs = new Set(MOTIFS.map((one) => one.id));
const arrangements = new Set(ARRANGEMENTS.map((one) => one.id));
const turns = new Set(TURNS.map((one) => one.id));

const problems: string[] = [];
const seen = new Set<string>();
const built = ALL.map((def) => {
  if (!/^[a-z][a-z0-9]*(-[a-z0-9]+)*$/.test(def.id)) problems.push(`${def.id}: not a kebab-case id`);
  if (seen.has(def.id)) problems.push(`${def.id}: duplicate id`);
  seen.add(def.id);
  if (!frames.has(def.frame)) problems.push(`${def.id}: unknown frame ${def.frame}`);
  for (const use of def.motifs) {
    if (!motifs.has(use.motif)) problems.push(`${def.id}: unknown motif ${use.motif}`);
    if (!arrangements.has(use.arrangement)) problems.push(`${def.id}: unknown arrangement ${use.arrangement}`);
    if (use.turn !== undefined && !turns.has(use.turn)) problems.push(`${def.id}: unknown turn ${use.turn}`);
  }
  const made = make(def);
  // Still traced: a stroke, or a curve that is not an arc. Such a crest has no construction to show yet, so it gives its finished
  // shapes only: no guides and no steps.
  const redrawing = made.shapes.some((shape) => shape.kind !== "fill" || /[^MmLlHhVvAaZz\d\s.,-]/.test(shape.d));
  const construction = redrawing ? { ...made, guides: [], steps: [], redrawing: true as const } : made;
  const allowed = new Set([...def.motifs.map((use) => use.motif), ...(def.frame === "none" ? [] : ["frame"])]);
  for (const shape of construction.shapes) if (!allowed.has(shape.part)) problems.push(`${def.id}: a shape belongs to ${shape.part}, which the crest does not list`);
  for (const part of allowed) if (!construction.shapes.some((shape) => shape.part === part)) problems.push(`${def.id}: part ${part} has no shape`);

  return { def, construction, made, redrawing, svg: staticSvg(construction) };
});
if (problems.length > 0) {
  console.error(problems.join("\n"));
  process.exit(1);
}

for (const dir of ["src/crests", "src/steps"]) {
  mkdirSync(dir, { recursive: true });
  for (const file of readdirSync(dir)) rmSync(`${dir}/${file}`);
}

const bytesOf = (text: string): number => Buffer.byteLength(text, "utf8");
const lines: string[] = [];
const records: unknown[] = [];

for (const { def, construction, made, redrawing, svg } of built) {
  writeFileSync(
    `src/crests/${def.id}.ts`,
    `${HEADER}
/**
 * The crest ${def.name.ja} (${def.name.en}), \`${def.id}\`, as an SVG string: viewBox 200 by 200, drawn in the page's text colour
 * (\`currentColor\`) with no background, ${construction.shapes.length} shapes, ${bytesOf(svg)} bytes. It is drawn from its compass-and-ruler
 * construction for this package, and is MIT like the rest of it.
 *
 * @example
 * \`\`\`ts no-run
 * import crest from "@johnmorrisdotca/kamon-crests/crests/${def.id}";
 *
 * const host = document.createElement("div");
 * host.innerHTML = crest;
 * console.log(host.querySelector("svg")?.getAttribute("viewBox")); // "0 0 200 200"
 * \`\`\`
 */
const svg = ${JSON.stringify(svg)};

export default svg;
export { svg };
`,
  );
  writeFileSync(
    `src/steps/${def.id}.ts`,
    `${HEADER}import type { Construction } from "../render";

/**
 * How ${def.name.en} (\`${def.id}\`) is constructed: its ${construction.guides.length} layout guides, its ${construction.shapes.length} shapes and the ${construction.steps.length} steps that draw them in order.
 *
 * @example
 * \`\`\`ts no-run
 * import construction from "@johnmorrisdotca/kamon-crests/steps/${def.id}";
 *
 * console.log(construction.steps.length); // ${construction.steps.length}
 * \`\`\`
 */
const construction: Construction = ${JSON.stringify(construction)};

export default construction;
export { construction };
`,
  );
  const secondsGuide = construction.guides.length;
  records.push({
    id: def.id,
    name: { en: def.name.en, ja: def.name.ja, reading: def.reading, romaji: def.romaji },
    frame: def.frame,
    motifs: def.motifs,
    families: def.families,
    aliases: def.aliases ?? [],
    construction: def.construction,
    usedBy: USED_BY[def.id] ?? [],
    bytes: bytesOf(svg),
    guides: secondsGuide,
    shapes: construction.shapes.length,
    steps: construction.steps.length,
    stats: statsOf(made),
    ...(redrawing ? { redrawing: true } : {}),
  });
  lines.push(`| \`${def.id}\` | ${def.name.ja} | ${def.name.en} | ${def.frame} | ${def.motifs.map((use) => `${use.motif} ×${use.count}`).join(", ")} | ${bytesOf(svg)} |`);
}

const ids = built.map(({ def }) => def.id);
writeFileSync("src/data/ids.data.ts", `${HEADER}
/**
 * The id of every crest, in the order of the catalogue.
 *
 * @example
 * \`\`\`ts
 * import { CREST_IDS } from "@johnmorrisdotca/kamon-crests";
 *
 * console.log(CREST_IDS.length > 50); // true
 * console.log(CREST_IDS.includes("mitsuba-aoi")); // true
 * \`\`\`
 */
export const CREST_IDS = ${JSON.stringify(ids)} as const;

/**
 * One of the ids of \`CREST_IDS\`.
 *
 * @example
 * \`\`\`ts
 * import type { CrestId } from "@johnmorrisdotca/kamon-crests";
 *
 * const id: CrestId = "janome";
 * console.log(id);
 * \`\`\`
 */
export type CrestId = (typeof CREST_IDS)[number];
`);
writeFileSync(
  "src/data/loaders.data.ts",
  `${HEADER}import type { Construction } from "../render";

/** Each crest's module, imported when it is asked for: a bundler makes a small chunk of each. */
export const LOADERS: Record<string, () => Promise<{ default: string }>> = {
${ids.map((id) => `  ${JSON.stringify(id)}: () => import("../crests/${id}.js"),`).join("\n")}
};

/** Each crest's construction, imported when its steps are asked for. */
export const STEP_LOADERS: Record<string, () => Promise<{ default: Construction }>> = {
${ids.map((id) => `  ${JSON.stringify(id)}: () => import("../steps/${id}.js"),`).join("\n")}
};
`,
);
writeFileSync("src/data/names.data.ts", `${HEADER}\n/** Each crest's name: English, then Japanese. Small, so that the element and the lookups can name a crest without the whole manifest. */\nexport const NAMES: Record<string, readonly [string, string]> = ${JSON.stringify(Object.fromEntries(built.map(({ def }) => [def.id, [def.name.en, def.name.ja]])))};\n`);
writeFileSync("src/data/records.data.ts", `${HEADER}import type { CrestRecord } from "../manifest.types";\n\n/** Every crest's record: names, parts, families, who uses it, and how big its drawing is. */\nexport const RECORDS: readonly CrestRecord[] = ${JSON.stringify(records, null, 1)};\n`);

mkdirSync("docs", { recursive: true });
const over = built.filter(({ svg }) => bytesOf(svg) > BUDGET_BYTES);
writeFileSync(
  "docs/sizes.md",
  `# Sizes

What a page pays for each crest. A crest's module is its SVG and a line of code; most are 1 to 4 KB. The budget for a
crest is ${BUDGET_BYTES / 1024} KB and the ceiling is ${CEILING_BYTES / 1024} KB; the crests over the budget are listed here with
the reason, and a test holds this list to the data. Written by \`pnpm data\`; do not edit it by hand.

## Over the budget

| Crest | Bytes | Why |
| --- | --- | --- |
${over.map(({ def, svg }) => `| \`${def.id}\` | ${bytesOf(svg)} | ${def.id.includes("aoi") ? "leaves of many small cells between their veins: many arcs" : def.id.includes("gashiwa") || def.id.includes("kiri") ? "scalloped leaves with fine veins cut out: many curves" : "many fine details"} |`).join("\n")}

## Worth knowing

- The main entry carries no crest: a page pays for the crests it imports, and for no others.
- The animation's data (\`/steps/<id>\`) is a separate module, loaded only when a crest is animated.
`,
);
writeFileSync(
  "docs/catalogue.md",
  `# The catalogue

${built.length} crests, in the order of the package. Written by \`pnpm data\`; do not edit it by hand.

| Id | 日本語 | English | Frame | Motifs | Bytes |
| --- | --- | --- | --- | --- | --- |
${lines.join("\n")}
`,
);

writeFileSync(
  "docs/provenance.md",
  `# Provenance: how each crest is constructed

Every drawing is made for this package and is MIT. The geometric crests are struck from their construction with compass and ruler.
The organic crests whose source is given below are vectorised from a public-domain period crest book: the page was read at the
National Diet Library, the crest's outline drawing was filled, traced to curves, cleaned of print noise, and made exactly symmetric
by keeping one half (or one leaf) and mirroring or turning it; no scan, crop or picture of the book is in the package or the
repository. This is the one-line rule each crest is set out by, in English and in Japanese, and the page it was drawn from.
Written by \`pnpm data\`; do not edit it by hand.

## Rings

The weight of a ring and the white inside it are measured from fifteen ringed crests drawn in the usual way (fourteen in a sheet of
ringed crests and one ringed chrysanthemum, the reference pictures the package was checked against): the ring is 0.079 to 0.095 of
the crest's diameter, 0.087 at the median; the white between ring and motif is 0.011 to 0.029 of the diameter, 0.018 at the median;
the motif reaches 0.77 to 0.80 of the outer radius. So a medium ring is 16.8 on the 192 of the layout circle, the white inside it 3.5,
and a ringed motif is drawn to the ring's inside less that white. A thin ring is a thirtieth of the diameter.

${built.map(({ def, construction }) => `## ${def.name.en} \u00b7 ${def.name.ja} (\`${def.id}\`)\n\n${def.construction.en}\n\n${def.construction.ja}\n\n${def.source === undefined ? "" : `Drawn from ${def.source.title} (${def.source.titleEn}), [NDL ${def.source.url.split("/").pop()}](${def.source.url}), frame ${def.source.frame}, ${def.source.place.en} (${def.source.place.ja}); public domain (保護期間満了); read ${def.source.read}.\n\n`}${construction.guides.length} guides, ${construction.shapes.length} shapes, ${construction.steps.length} steps.`).join("\n\n")}
`,
);

// Every Japanese string in the data, with its English, for the reviewer.
const ja: string[] = [];
const row = (where: string, jaText: string, enText: string): void => void ja.push(`| ${where} | ${jaText.replace(/\|/g, "\\|")} | ${enText.replace(/\|/g, "\\|")} |`);
for (const group of [FRAMES, MOTIFS, ARRANGEMENTS, TURNS]) {
  for (const one of group) {
    row(`term \`${one.id}\``, `${one.ja} (${one.reading})`, one.en);
    row(`term \`${one.id}\` about`, one.about.ja, one.about.en);
  }
}
for (const { def } of built) {
  row(`\`${def.id}\` name`, `${def.name.ja} (${def.reading})`, def.name.en);
  row(`\`${def.id}\` construction`, def.construction.ja, def.construction.en);
  if (def.source !== undefined) row(`\`${def.id}\` source, place`, def.source.place.ja, def.source.place.en);
  for (const family of def.families) row(`\`${def.id}\` family`, `${family.ja}${family.reading === undefined ? "" : ` (${family.reading})`}`, family.en);
  for (const user of USED_BY[def.id] ?? []) {
    row(`\`${def.id}\` used by`, user.name.ja, user.name.en);
    row(`\`${def.id}\` used by, note`, user.note.ja, user.note.en);
  }
}
for (const key of Object.keys(WORDS.ja)) row(`demo \`${key}\``, WORDS.ja[key], WORDS.en[key] ?? "");
writeFileSync(
  "docs/strings-ja.md",
  `# Japanese strings in the data

Every Japanese string the data and the demo hold, with its English, for a native reader to review. Written by \`pnpm data\`; do not edit it by hand. Corrections go in the source (\`src/parts.ts\`, \`scripts/crests/\`).

| Where | 日本語 | English |
| --- | --- | --- |
${ja.join("\n")}
`,
);
console.log(`${built.length} crests written`);
