// Writes everything generated from the crest definitions: each crest's module and its construction, the table of
// loaders, the records, and the catalogue and Japanese-string lists in docs/. Run it with `pnpm data`; CI runs it
// again and fails if anything it writes differs from what is committed.
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";

import { staticSvg } from "../src/render.ts";
import { ARRANGEMENTS, FRAMES, MOTIFS, TURNS } from "../src/parts.ts";
import { make } from "./construct/make.ts";
import { statsOf } from "./construct/stats.ts";
import { ALL } from "./crests/index.ts";
import { CHAPTERS, FAMILIES, placeAll } from "./crests/families.ts";
import { NUMBERS } from "./crests/numbers.ts";
import { USED_BY } from "./crests/used-by.ts";
import { BUDGET_BYTES, CEILING_BYTES } from "./data-config.ts";
import { WORDS } from "../demo/words.js";

const HEADER = "// Generated by scripts/build-data.ts. Do not edit by hand: change the crest's definition in scripts/crests and run pnpm data.\n";
const frames = new Set(FRAMES.map((one) => one.id));
const motifs = new Set(MOTIFS.map((one) => one.id));
const arrangements = new Set(ARRANGEMENTS.map((one) => one.id));
const turns = new Set(TURNS.map((one) => one.id));

const problems: string[] = [];
const seen = new Set<string>();
const built = ALL.map((def) => {
  if (!/^[a-z][a-z0-9]*(-[a-z0-9]+)*$/.test(def.id)) problems.push(`${def.id}: not a kebab-case id`);
  if (seen.has(def.id)) problems.push(`${def.id}: duplicate id`);
  seen.add(def.id);
  if (!frames.has(def.frame)) problems.push(`${def.id}: unknown frame ${def.frame}`);
  for (const use of def.motifs) {
    if (!motifs.has(use.motif)) problems.push(`${def.id}: unknown motif ${use.motif}`);
    if (!arrangements.has(use.arrangement)) problems.push(`${def.id}: unknown arrangement ${use.arrangement}`);
    if (use.turn !== undefined && !turns.has(use.turn)) problems.push(`${def.id}: unknown turn ${use.turn}`);
  }
  const made = make(def);
  // Still traced: a stroke, or a curve that is not an arc. Such a crest has no construction to show yet, so it gives its finished
  // shapes only: no guides and no steps.
  const redrawing = made.shapes.some((shape) => shape.kind !== "fill" || /[^MmLlHhVvAaZz\d\s.,-]/.test(shape.d));
  const construction = redrawing ? { ...made, guides: [], steps: [], redrawing: true as const } : made;
  const allowed = new Set([...def.motifs.map((use) => use.motif), ...(def.frame === "none" ? [] : ["frame"])]);
  for (const shape of construction.shapes) if (!allowed.has(shape.part)) problems.push(`${def.id}: a shape belongs to ${shape.part}, which the crest does not list`);
  for (const part of allowed) if (!construction.shapes.some((shape) => shape.part === part)) problems.push(`${def.id}: part ${part} has no shape`);

  return { def, construction, made, redrawing, svg: staticSvg(construction) };
});
const { places, problems: placing } = placeAll(ALL);
problems.push(...placing);
if (problems.length > 0) {
  console.error(problems.join("\n"));
  process.exit(1);
}

// The books' order: chapter, then the family by the reading of its name (gojūon), then the base, the forms, the tones, the counts, the
// frames, the arrangements, the combinations and the houses' variants. The catalogue number of a crest is its place in this order when it
// is first numbered, and it never changes: scripts/crests/numbers.ts is the ledger, and a crest it does not hold takes the next number.
const collator = new Intl.Collator("ja");
const familyOf = new Map(FAMILIES.map((one) => [one.id, one]));
const chapterAt = (id: string): number => CHAPTERS.findIndex((one) => one.id === id);
const familyOrder = [...FAMILIES].sort((a, b) => chapterAt(a.chapter) - chapterAt(b.chapter) || collator.compare(a.reading, b.reading) || (a.id < b.id ? -1 : 1));
const familyAt = new Map(familyOrder.map((one, at) => [one.id, at]));
const placeOf = (id: string) => places.get(id) as NonNullable<ReturnType<typeof places.get>>;
built.sort((a, b) => {
  const [pa, pb] = [placeOf(a.def.id), placeOf(b.def.id)];

  return (familyAt.get(pa.family) as number) - (familyAt.get(pb.family) as number) || pa.position - pb.position;
});
const numbers: Record<string, number> = { ...NUMBERS };
let next = Math.max(0, ...Object.values(numbers)) + 1;
const fresh = built.filter(({ def }) => numbers[def.id] === undefined).map(({ def }) => def.id);
for (const id of fresh) numbers[id] = next++;
if (fresh.length > 0) {
  const ledger = Object.entries(numbers).sort((a, b) => a[1] - b[1]);
  writeFileSync("scripts/crests/numbers.ts", `// The catalogue number of every crest, in the order the crests were first numbered (the books' order then). A number is never changed and never used twice,\n// not even for a crest taken out. \`pnpm data\` adds each new crest at the end, in the books' order among the new ones; commit what it writes.\nexport const NUMBERS: Record<string, number> = {\n${ledger.map(([id, n]) => `  ${JSON.stringify(id)}: ${n},`).join("\n")}\n};\n`);
  console.log(`numbered ${fresh.length} new crests: ${fresh.join(", ")}`);
}
const seenNumbers = new Set<number>();
for (const { def } of built) {
  if (seenNumbers.has(numbers[def.id])) problems.push(`${def.id}: catalogue number ${numbers[def.id]} is used twice`);
  seenNumbers.add(numbers[def.id]);
}
if (problems.length > 0) {
  console.error(problems.join("\n"));
  process.exit(1);
}

for (const dir of ["src/crests", "src/steps"]) {
  mkdirSync(dir, { recursive: true });
  for (const file of readdirSync(dir)) rmSync(`${dir}/${file}`);
}

const bytesOf = (text: string): number => Buffer.byteLength(text, "utf8");
const lines: string[] = [];
const records: unknown[] = [];

for (const { def, construction, made, redrawing, svg } of built) {
  writeFileSync(
    `src/crests/${def.id}.ts`,
    `${HEADER}
/**
 * The crest ${def.name.ja} (${def.name.en}), \`${def.id}\`, as an SVG string: viewBox 200 by 200, drawn in the page's text colour
 * (\`currentColor\`) with no background, ${construction.shapes.length} shapes, ${bytesOf(svg)} bytes. It is drawn from its compass-and-ruler
 * construction for this package, and is MIT like the rest of it.
 *
 * @example
 * \`\`\`ts no-run
 * import crest from "@johnmorrisdotca/kamon-crests/crests/${def.id}";
 *
 * const host = document.createElement("div");
 * host.innerHTML = crest;
 * console.log(host.querySelector("svg")?.getAttribute("viewBox")); // "0 0 200 200"
 * \`\`\`
 */
const svg = ${JSON.stringify(svg)};

export default svg;
export { svg };
`,
  );
  writeFileSync(
    `src/steps/${def.id}.ts`,
    `${HEADER}import type { Construction } from "../render";

/**
 * How ${def.name.en} (\`${def.id}\`) is constructed: its ${construction.guides.length} layout guides, its ${construction.shapes.length} shapes and the ${construction.steps.length} steps that draw them in order.
 *
 * @example
 * \`\`\`ts no-run
 * import construction from "@johnmorrisdotca/kamon-crests/steps/${def.id}";
 *
 * console.log(construction.steps.length); // ${construction.steps.length}
 * \`\`\`
 */
const construction: Construction = ${JSON.stringify(construction)};

/**
 * How ${def.name.en} (\`${def.id}\`) is constructed, in a line in each language: the text a crest's card shows beside its steps.
 * It is here, not on the crest's record, so that the manifest stays small; \`crestConstruction()\` loads it.
 *
 * @example
 * \`\`\`ts no-run
 * import { description } from "@johnmorrisdotca/kamon-crests/steps/${def.id}";
 *
 * console.log(description.en.length > 30, description.ja.endsWith("。")); // true true
 * \`\`\`
 */
const description: { en: string; ja: string } = ${JSON.stringify(def.construction)};

export default construction;
export { construction, description };
`,
  );
  const secondsGuide = construction.guides.length;
  records.push({
    id: def.id,
    no: numbers[def.id],
    name: { en: def.name.en, ja: def.name.ja, reading: def.reading, romaji: def.romaji },
    family: placeOf(def.id).family,
    familyReading: (familyOf.get(placeOf(def.id).family) as { reading: string }).reading,
    base: placeOf(def.id).base,
    variantKind: placeOf(def.id).variantKind,
    variantRank: placeOf(def.id).variantRank,
    frame: def.frame,
    motifs: def.motifs,
    families: def.families,
    aliases: def.aliases ?? [],
    ...(def.note === undefined ? {} : { note: def.note }),
    usedBy: USED_BY[def.id] ?? [],
    bytes: bytesOf(svg),
    guides: secondsGuide,
    shapes: construction.shapes.length,
    steps: construction.steps.length,
    stats: statsOf(made),
    ...(redrawing ? { redrawing: true } : {}),
  });
  const place = placeOf(def.id);
  lines.push(`| ${numbers[def.id]} | \`${def.id}\` | ${def.name.ja} | ${def.name.en} | ${place.family} | ${place.variantKind} | ${def.frame} | ${def.motifs.map((use) => `${use.motif} ×${use.count}`).join(", ")} | ${bytesOf(svg)} |`);
}

const ids = built.map(({ def }) => def.id);
writeFileSync("src/data/ids.data.ts", `${HEADER}
/**
 * The id of every crest, in the order of the catalogue.
 *
 * @example
 * \`\`\`ts
 * import { CREST_IDS } from "@johnmorrisdotca/kamon-crests";
 *
 * console.log(CREST_IDS.length > 50); // true
 * console.log(CREST_IDS.includes("mitsuba-aoi")); // true
 * \`\`\`
 */
export const CREST_IDS = ${JSON.stringify(ids)} as const;

/**
 * One of the ids of \`CREST_IDS\`.
 *
 * @example
 * \`\`\`ts
 * import type { CrestId } from "@johnmorrisdotca/kamon-crests";
 *
 * const id: CrestId = "janome";
 * console.log(id);
 * \`\`\`
 */
export type CrestId = (typeof CREST_IDS)[number];
`);
writeFileSync(
  "src/data/loaders.data.ts",
  `${HEADER}import type { Construction } from "../render";

/** Each crest's module, imported when it is asked for: a bundler makes a small chunk of each. */
export const LOADERS: Record<string, () => Promise<{ default: string }>> = {
${ids.map((id) => `  ${JSON.stringify(id)}: () => import("../crests/${id}.js"),`).join("\n")}
};

/** Each crest's construction and its text, imported when its steps or its text are asked for. */
export const STEP_LOADERS: Record<string, () => Promise<{ default: Construction; description: { en: string; ja: string } }>> = {
${ids.map((id) => `  ${JSON.stringify(id)}: () => import("../steps/${id}.js"),`).join("\n")}
};
`,
);
writeFileSync("src/data/names.data.ts", `${HEADER}\n/** Each crest's name: English, then Japanese. Small, so that the element and the lookups can name a crest without the whole manifest. */\nexport const NAMES: Record<string, readonly [string, string]> = ${JSON.stringify(Object.fromEntries(built.map(({ def }) => [def.id, [def.name.en, def.name.ja]])))};\n`);
writeFileSync(
  "src/data/families.data.ts",
  `${HEADER}import type { Chapter, MotifFamily } from "../manifest.types";\n\n/** The seven chapters of the crest books, in their order. */\nexport const CHAPTER_LIST: readonly Chapter[] = ${JSON.stringify(CHAPTERS)};\n\n/** Every motif family, in the books' order: by chapter, then by the reading of its name. */\nexport const FAMILY_LIST: readonly MotifFamily[] = ${JSON.stringify(familyOrder.map((one) => ({ id: one.id, chapter: one.chapter, ja: one.ja, reading: one.reading, en: one.en, base: one.base })))};\n`,
);
writeFileSync("src/data/records.data.ts", `${HEADER}import type { CrestRecord } from "../manifest.types";\n\n/** Every crest's record: names, parts, families, who uses it, and how big its drawing is. */\nexport const RECORDS: readonly CrestRecord[] = ${JSON.stringify(records)};\n`);

mkdirSync("docs", { recursive: true });
const over = built.filter(({ svg }) => bytesOf(svg) > BUDGET_BYTES);
writeFileSync(
  "docs/sizes.md",
  `# Sizes

What a page pays for each crest. A crest's module is its SVG and a line of code; most are 1 to 4 KB. The budget for a
crest is ${BUDGET_BYTES / 1024} KB and the ceiling is ${CEILING_BYTES / 1024} KB; the crests over the budget are listed here with
the reason, and a test holds this list to the data. Written by \`pnpm data\`; do not edit it by hand.

## Over the budget

| Crest | Bytes | Why |
| --- | --- | --- |
${over.map(({ def, svg }) => `| \`${def.id}\` | ${bytesOf(svg)} | ${def.id.includes("aoi") ? "leaves of many small cells between their veins: many arcs" : def.id.includes("gashiwa") || def.id.includes("kiri") ? "scalloped leaves with fine veins cut out: many curves" : "many fine details"} |`).join("\n")}

## Worth knowing

- The main entry carries no crest: a page pays for the crests it imports, and for no others.
- The animation's data (\`/steps/<id>\`) is a separate module, loaded only when a crest is animated.
- \`/load\` is the table of every crest's two loaders, so it grows about 155 bytes with each crest, and a flat limit would fail on every new crest. Its budget is counted by the crest: 3.5 KB for its own code and 140 bytes a crest. That still catches a loader that grows per crest.
- \`/animate\` was held to 25 KB (it was 24.0 KB) and is now held to 36 KB (it is 35.1 KB); the element was held to 12 KB (it was 12.0 KB) and is now held to 14 KB (it is 13.6 KB). Three switches of the animation account for it, and nothing else grew: the widths key (its rows, laid out in columns for a crest of many widths, bold while the compass is set to that width, and the element's wider box to hold it), the pen's ink (the length of each outline, the pace of each trace and thickening, the heavy second outline) and every place built in full (\`fullBuilt\`, which writes each place's circles and lines where they stand, and the place's caption). Each budget is the built file's size plus under a kilobyte, so a fourth switch would have to ask again.
- \`/animate\` is now held to 37 KB (it is 36.5 KB): the guides' flash before they are rubbed out (a wider, full-strength stop in each guide's keyframes and one for their group) took it past 36 KB.
- \`/animate\` is now held to 38 KB (it is 37.3 KB): the widths key became a ruler (a tick and a number for every width, the numbers set out in two rows where they fit, and the width of each arc the pen inks marked on it) and took it past 37 KB.
- \`/animate\` is now held to 39 KB (it is 38.1 KB): a step that only repeats an earlier step's shape (outlined, thickened or filled again at another place) now plays twice as fast, and finding those steps took it past 38 KB.
- \`/animate\` is now held to 42 KB (it is 40.6 KB): a browser starts a path's dashes again at each of its subpaths, so a ring or a shape with a hole was inked round all its subpaths at once, ahead of the compass arm; each subpath is now drawn as its own outline in its share of the time, which took it past 39 KB.
- The manifest is held to 4 KB and 800 bytes a crest, down from 1,350: a record no longer carries its \`construction\` text (English and Japanese, 54% of the records' field data), which now loads with the crest's steps through \`crestConstruction(id)\`, so no page that lists, searches or sorts the crests pays for it. The manifest fell from 164,515 to 96,371 bytes, about 775 bytes a crest, so the 800 leaves about 3% of headroom.
- A crest's \`/steps/<id>\` module is held to 50 KB, up from 48 KB: it now also holds the crest's construction text, up to about 1.4 KB, and the largest (\`agehacho\`) went from about 48.6 KB to 50.0 KB. The text rides in the steps module, not in a chunk of its own, because the card already loads the steps, and a second table of loaders would have added to \`/load\` for every crest.
- \`/names\` is the table of every crest's id and its two names, so it grows about 64 bytes with each crest (a short name about 35, a long framed one about 90), and its flat 6 KB limit would have failed near 95 crests. Its budget is counted by the crest too: 0.5 KB for its own code and 72 bytes a crest. That still catches a table that gains a third string per crest.
`,
);
