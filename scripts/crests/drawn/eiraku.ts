const point = (text: string): V => {
  const [x, y] = text.split(",").map(Number);

  return [x, y];
};

/** The circle through three points. */
const through = (a: V, m: V, b: V): Circle => {
  const d = 2 * (a[0] * (m[1] - b[1]) + m[0] * (b[1] - a[1]) + b[0] * (a[1] - m[1]));
  const sq = (p: V): number => p[0] * p[0] + p[1] * p[1];
  const x = (sq(a) * (m[1] - b[1]) + sq(m) * (b[1] - a[1]) + sq(b) * (a[1] - m[1])) / d;
  const y = (sq(a) * (b[0] - m[0]) + sq(m) * (a[0] - b[0]) + sq(b) * (m[0] - a[0])) / d;

  return { c: [x, y], r: Math.hypot(a[0] - x, a[1] - y) };
};

export const outline = (loop: string[]): Region =>
  loop.map((text) => {
    const [a, b, m] = text.split(" ").map(point) as [V, V, V | undefined];
    if (m === undefined) return seg(a, b);
    const turn = (m[0] - a[0]) * (b[1] - m[1]) - (m[1] - a[1]) * (b[0] - m[0]);

    return arcTo(through(a, m, b), a, b, turn > 0);
  });

const square = (half: number): Region => {
  const corners: V[] = [[-half, half], [half, half], [half, -half], [-half, -half]];

  return corners.map((p, i) => seg(p, corners[(i + 1) % 4]));
};

/**
 * The Yongle coin: the ring first, then the two square frames round the hole (each 2 wide, the outer one 31 out from the middle
 * and the inner one 21), then the four characters. The book's coin is 94 in its own units; the strokes are drawn at 0.93 of them.
 */
export const eirakuBuild = (c: Builder, part: string): void => {
  c.ring("ring-thin");
  const placing: Placing = { k: 0.93 };
  c.guideCircle(C0, 96);
  c.fill(part, toPath([square(32), square(30)], placing), "evenodd");
  c.fill(part, toPath([square(22), square(20)], placing), "evenodd");
  c.fill(part, toPath(STROKES.map(outline), placing), "evenodd");
};
