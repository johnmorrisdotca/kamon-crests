/** A wave in a thin ring: the left half of the wave, then the same mirrored. */
const waveBuild = (c: Builder, part: string, loops: string[][]): void => {
  c.ring("ring-thin");
  const left = loops.map(outline);
  c.fill(part, toPath(left, PLACING), "evenodd");
  c.fill(part, toPath(left.map((loop) => loop.map(mirrored)), PLACING), "evenodd");
};

/** 丸に抱き波: the embracing waves of the 1892 book's cell, solid, in a thin ring. */
export const maruNiDakiNamiBuild = (c: Builder, part: string): void => waveBuild(c, part, DAKI_NAMI);
