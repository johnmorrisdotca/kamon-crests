// Writes docs/coverage.md: every named crest the books list (docs/coverage/kamon.json), each marked drawn or missing, with the counts
// by chapter and by family and a checklist of what is still to draw. `pnpm coverage` builds the package first, then runs this.
// Matching is by the Japanese name, then our other names, then the reading: see scripts/coverage-data.mjs.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import process from "node:process";

import { coverage } from "./coverage-data.mjs";

const root = join(import.meta.dirname, "..");

const percent = (counts) => `${counts.percent.toFixed(1)}%`;
const money = (n) => n.toLocaleString("en-US");
const line = (entry) => {
  const name = `${entry.ja} (${entry.romaji}) — ${entry.en}`;
  if (entry.have !== null) return `- [x] ${name}${entry.extra === true ? " · ours only, not in the list" : ` · tier ${entry.tier}`} → \`${entry.have}\``;
  const houses = (entry.houses ?? []).length > 0 ? ` · houses ${entry.houses.join(", ")}` : "";

  return `- [ ] ${name} · tier ${entry.tier}${houses}`;
};
// Drawn first, then the missing, tier 1 before tier 2 before tier 3, then by reading.
const order = (a, b) => (a.have === null) - (b.have === null) || (a.tier ?? 0) - (b.tier ?? 0) || (a.reading ?? "").localeCompare(b.reading ?? "", "ja");

export function coverageMarkdown({ chapters, total, ours }) {
  const out = [
    "# Coverage",
    "",
    "Generated by `pnpm data` or `pnpm coverage`. Do not edit by hand.",
    "",
    `Every named crest the crest books list (\`docs/coverage/kamon.json\`), by chapter, each marked as drawn by this package or still missing. ${money(total.have)} of ${money(total.total)} are drawn (${percent(total)}). The ${ours} crests the package has are all counted: any the list does not name is added to it, marked "ours only". Tier 1 is a family's base form and the famous crests, tier 2 the common named variants, tier 3 the rarer ones. The same list is on the demo's [Coverage page](https://johnmorrisdotca.github.io/kamon-crests/coverage/).`,
    "",
    "## By chapter",
    "",
    "| Chapter | Drawn | Total | % | Missing tier 1 | Missing tier 2 |",
    "| --- | ---: | ---: | ---: | ---: | ---: |",
    ...chapters.map((chapter) => `| ${chapter.ja} ${chapter.en} | ${chapter.have} | ${chapter.total} | ${percent(chapter)} | ${chapter.tier1} | ${chapter.tier2} |`),
    `| **All** | **${total.have}** | **${total.total}** | **${percent(total)}** | **${total.tier1}** | **${total.tier2}** |`,
    "",
  ];

  for (const chapter of chapters) {
    out.push(`## ${chapter.ja} ${chapter.en}`, "", `${chapter.have} of ${chapter.total} drawn (${percent(chapter)}).`, "");
    if (chapter.total === 0) {
      out.push("Nothing listed yet.", "");
      continue;
    }
    out.push("Families, the ones with the most still to draw first:", "", "| Family | Drawn | Total | Missing |", "| --- | ---: | ---: | ---: |");
    for (const family of chapter.families) out.push(`| ${family.family}${family.en === "" ? "" : ` ${family.en}`} | ${family.have} | ${family.total} | ${family.missing} |`);
    out.push("");
    for (const family of chapter.families) {
      out.push(`### ${family.family}${family.en === "" ? "" : ` (${family.en})`}: ${family.have} of ${family.total}`, "", ...[...family.entries].sort(order).map(line), "");
    }
  }
  return out.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
}

if (import.meta.main) {
  const data = await coverage();
  const { total, ours, entries } = data;
  const extras = entries.filter((entry) => entry.extra === true);
  writeFileSync(join(root, "docs", "coverage.md"), coverageMarkdown(data));
  console.log(`docs/coverage.md: ${total.have} of ${total.total} drawn (${percent(total)}); ${extras.length} of our ${ours} crests are in no entry${extras.length === 0 ? "" : `: ${extras.map((entry) => entry.ja).join(", ")}`}.`);
  if (total.have !== ours) {
    console.error(`The counts disagree: ${total.have} drawn, ${ours} crests in the package.`);
    process.exitCode = 1;
  }
}
